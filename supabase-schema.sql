   ========================================================= */

drop policy if exists
"profiles_select_authenticated"
on public.profiles;

drop policy if exists
"profiles_insert_own"
on public.profiles;

drop policy if exists
"profiles_update_own"
on public.profiles;


/* =========================================================
   12. PROFILE SELECT POLICY
   ========================================================= */

create policy
"profiles_select_authenticated"

on public.profiles

for select

to authenticated

using (
  true
);


/* =========================================================
   13. PROFILE INSERT POLICY
   ========================================================= */

create policy
"profiles_insert_own"

on public.profiles

for insert

to authenticated

with check (
  auth.uid() = id
);


/* =========================================================
   14. PROFILE UPDATE POLICY
   ========================================================= */

create policy
"profiles_update_own"

on public.profiles

for update

to authenticated

using (
  auth.uid() = id
)

with check (
  auth.uid() = id
);


/* =========================================================
   15. REMOVE OLD MESSAGE POLICIES
   ========================================================= */

drop policy if exists
"messages_select_participants"
on public.messages;

drop policy if exists
"messages_insert_sender"
on public.messages;

drop policy if exists
"messages_update_recipient"
on public.messages;

drop policy if exists
"messages_delete_participants"
on public.messages;


/* =========================================================
   16. MESSAGE SELECT POLICY
   ========================================================= */

create policy
"messages_select_participants"

on public.messages

for select

to authenticated

using (
  auth.uid() = sender_id
  or
  auth.uid() = receiver_id
);


/* =========================================================
   17. MESSAGE INSERT POLICY
   ========================================================= */

create policy
"messages_insert_sender"

on public.messages

for insert

to authenticated

with check (
  auth.uid() = sender_id
);


/* =========================================================
   18. MESSAGE UPDATE POLICY
   =========================================================
   
   Mainly used for read_at.
   Only the receiver can update
   received messages.
   ========================================================= */

create policy
"messages_update_recipient"

on public.messages

for update

to authenticated

using (
  auth.uid() = receiver_id
)

with check (
  auth.uid() = receiver_id
);


/* =========================================================
   19. MESSAGE DELETE POLICY
   =========================================================
   
   Allows either participant to clear
   messages from their conversation.
   ========================================================= */

create policy
"messages_delete_participants"

on public.messages

for delete

to authenticated

using (
  auth.uid() = sender_id
  or
  auth.uid() = receiver_id
);


/* =========================================================
   20. REALTIME — MESSAGES
