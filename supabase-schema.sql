   ========================================================= */


/* =========================================================
   1. PROFILES TABLE
   ========================================================= */

create table if not exists public.profiles (
  id uuid primary key
    references auth.users(id)
    on delete cascade,

  display_name text not null default 'User',

  avatar_url text,

  created_at timestamptz not null default now(),

  last_seen timestamptz,

  is_online boolean not null default false,

  last_logout_at timestamptz
);


/* =========================================================
   2. ADD MISSING PROFILE COLUMNS
   ========================================================= */

alter table public.profiles
  add column if not exists display_name text;

alter table public.profiles
  add column if not exists avatar_url text;

alter table public.profiles
  add column if not exists created_at timestamptz
  default now();

alter table public.profiles
  add column if not exists last_seen timestamptz;

alter table public.profiles
  add column if not exists is_online boolean
  default false;

alter table public.profiles
  add column if not exists last_logout_at timestamptz;


/* =========================================================
   3. FIX POSSIBLE NULL VALUES
   ========================================================= */

update public.profiles
set display_name = 'User'
where display_name is null;

update public.profiles
set is_online = false
where is_online is null;


/* =========================================================
   4. PROFILES DEFAULTS
   ========================================================= */

alter table public.profiles
  alter column display_name
  set default 'User';

alter table public.profiles
  alter column is_online
  set default false;


/* =========================================================
   5. MESSAGES TABLE
   ========================================================= */

create table if not exists public.messages (

  id bigint
    generated by default as identity
    primary key,

  sender_id uuid not null
    references public.profiles(id)
    on delete cascade,

  receiver_id uuid not null
    references public.profiles(id)
    on delete cascade,

  content text not null default '',

  message_type text not null default 'text',

  file_url text,

  file_name text,

  file_size bigint,

  created_at timestamptz not null default now(),

  read_at timestamptz
);


/* =========================================================
   6. ADD MISSING MESSAGE COLUMNS
   ========================================================= */

alter table public.messages
  add column if not exists content text
  default '';

alter table public.messages
  add column if not exists message_type text
  default 'text';

alter table public.messages
  add column if not exists file_url text;

alter table public.messages
  add column if not exists file_name text;

alter table public.messages
  add column if not exists file_size bigint;

alter table public.messages
  add column if not exists created_at timestamptz
  default now();

alter table public.messages
  add column if not exists read_at timestamptz;


/* =========================================================
   7. FIX OLD NULL VALUES
   ========================================================= */

update public.messages
set content = ''
where content is null;

update public.messages
set message_type = 'text'
where message_type is null;


/* =========================================================
   8. DEFAULTS
   ========================================================= */

alter table public.messages
  alter column content
  set default '';

alter table public.messages
  alter column message_type
  set default 'text';


/* =========================================================
   9. INDEXES
   ========================================================= */

create index if not exists
messages_sender_receiver_created_idx
on public.messages (
  sender_id,
  receiver_id,
  created_at
);


create index if not exists
messages_receiver_sender_created_idx
on public.messages (
  receiver_id,
  sender_id,
  created_at
);


create index if not exists
messages_receiver_read_idx
on public.messages (
  receiver_id,
  read_at
);


create index if not exists
messages_created_at_idx
on public.messages (
  created_at
);


create index if not exists
profiles_last_seen_idx
on public.profiles (
  last_seen
);


/* =========================================================
   10. ENABLE ROW LEVEL SECURITY
   ========================================================= */

alter table public.profiles
enable row level security;

alter table public.messages
enable row level security;


